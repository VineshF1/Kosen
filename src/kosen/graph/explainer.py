from __future__ import annotations
from typing import Optional
from datetime import datetime

from kosen.schemas import VerifiedFinding, VerificationStatus, FindingSeverity, FindingCategory


def format_verified_finding(finding: VerifiedFinding) -> str:
    """Format a single verified finding for PR comment."""
    candidate = finding.candidate
    
    # Severity emoji
    severity_emoji = {
        FindingSeverity.CRITICAL: "🔴",
        FindingSeverity.HIGH: "🟠",
        FindingSeverity.MEDIUM: "🟡",
        FindingSeverity.LOW: "🟢",
        FindingSeverity.INFO: "🔵",
    }.get(candidate.severity, "⚪")
    
    # Category emoji
    category_emoji = {
        FindingCategory.SECURITY: "🔒",
        FindingCategory.PERFORMANCE: "⚡",
        FindingCategory.SYNTAX: "🔧",
        FindingCategory.COVERAGE: "📊",
    }.get(candidate.category, "📝")
    
    # Verification status
    status_emoji = {
        VerificationStatus.VERIFIED: "✅",
        VerificationStatus.UNGATED_ADVISORY: "⚠️",
        VerificationStatus.REJECTED: "❌",
        VerificationStatus.ERROR: "💥",
    }.get(finding.verification_status, "❓")
    
    lines = [
        f"### {status_emoji} {category_emoji} {severity_emoji} {candidate.title}",
        "",
        f"**Category:** {candidate.category.value.title()}  ",
        f"**Severity:** {candidate.severity.value.title()}  ",
        f"**File:** `{candidate.location.file_path}` (lines {candidate.location.start_line}-{candidate.location.end_line})  ",
        f"**Verification:** {finding.verification_status.value.replace('_', ' ').title()} via `{finding.verification_tool}`  ",
        f"**False Positive Risk:** {finding.false_positive_risk:.0%}",
        "",
        f"**Description:** {candidate.description}",
        "",
    ]
    
    if candidate.snippet:
        lines.extend([
            "**Code Snippet:**",
            "```python",
            candidate.snippet,
            "```",
            "",
        ])
    
    if candidate.suggested_fix:
        lines.extend([
            "**Suggested Fix:**",
            "```python",
            candidate.suggested_fix,
            "```",
            "",
        ])
    
    lines.extend([
        f"*Reasoning: {candidate.reasoning}*",
        "",
        "---",
        "",
    ])
    
    return "\n".join(lines)


def format_pr_comment(findings: list[VerifiedFinding]) -> str:
    """Format all verified findings as a PR review comment."""
    if not findings:
        return "## 🤖 Kosen Code Review\n\n✅ No issues found. Code looks good!"
    
    # Group by verification status
    verified = [f for f in findings if f.verification_status == VerificationStatus.VERIFIED]
    ungated = [f for f in findings if f.verification_status == VerificationStatus.UNGATED_ADVISORY]
    rejected = [f for f in findings if f.verification_status == VerificationStatus.REJECTED]
    errors = [f for f in findings if f.verification_status == VerificationStatus.ERROR]
    
    lines = [
        "## 🤖 Kosen Code Review",
        "",
        f"**Summary:** {len(verified)} verified, {len(ungated)} advisory, {len(rejected)} rejected, {len(errors)} errors",
        "",
        "---",
        "",
    ]
    
    if verified:
        lines.append("### ✅ Verified Findings (Static Tool Confirmed)")
        lines.append("")
        for f in verified:
            lines.append(format_verified_finding(f))
    
    if ungated:
        lines.append("### ⚠️ Ungated Advisories (LLM Only - No Static Tool Corroboration)")
        lines.append("")
        for f in ungated:
            lines.append(format_verified_finding(f))
    
    if rejected:
        lines.append("### ❌ Rejected Candidates (Static Tools Found No Evidence)")
        lines.append("")
        for f in rejected:
            lines.append(format_verified_finding(f))
    
    if errors:
        lines.append("### 💥 Errors During Verification")
        lines.append("")
        for f in errors:
            lines.append(format_verified_finding(f))
    
    lines.extend([
        "",
        "---",
        "",
        f"*Generated by Kosen Agentic Code Reviewer at {datetime.utcnow().isoformat()}Z*",
    ])
    
    return "\n".join(lines)


def format_summary(findings: list[VerifiedFinding]) -> str:
    """Format a concise summary for PR check status."""
    if not findings:
        return "✅ No issues found"
    
    verified = [f for f in findings if f.verification_status == VerificationStatus.VERIFIED]
    critical = [f for f in verified if f.candidate.severity == FindingSeverity.CRITICAL]
    high = [f for f in verified if f.candidate.severity == FindingSeverity.HIGH]
    
    parts = []
    if critical:
        parts.append(f"🔴 {len(critical)} critical")
    if high:
        parts.append(f"🟠 {len(high)} high")
    if verified:
        parts.append(f"✅ {len(verified)} verified")
    
    ungated = len([f for f in findings if f.verification_status == VerificationStatus.UNGATED_ADVISORY])
    if ungated:
        parts.append(f"⚠️ {ungated} advisory")
    
    return " | ".join(parts) if parts else "✅ No issues found"